const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
let processed=0;
const scope={window:{},URL,document:{currentScript:{src:'http://localhost/js/scan-renderer.js'},createElement:()=>({width:0,height:0,getContext:()=>({fillRect(){},drawImage(){}})})},applyFilterToContext(){processed++;},console};
vm.runInNewContext(fs.readFileSync('public/js/scan-renderer.js','utf8'),scope);
(async()=>{
 const image={width:1200,height:1600};
 const r=scope.window.ScanRenderer;
 const skipped=await r.render(image,'magicpro',{},()=>false);
 assert.equal(skipped,null);assert.equal(processed,0);
 const first=await r.render(image,'magicpro');
 const reused=await r.render(image,'magicpro');
 assert.equal(first,reused);assert.equal(processed,1);
 assert.equal(first.width,1200);assert.equal(first.height,1600);
 await r.render(image,'enhance');assert.equal(processed,2);
 await r.render(image,'original');assert.equal(processed,2);
 await r.render(image,'original',{contrast:10});assert.equal(processed,3);
 const preview=await r.preview(image,'magicpro');
 assert.ok(preview.width*preview.height<=1_402_000,'Preview has a bounded pixel budget');
 assert.equal(preview.height,Math.round(1600*Math.sqrt(1_400_000/(1200*1600))));
 const afterPreview=processed;
 await r.preview(image,'bw');
 assert.equal(await r.preview(image,'magicpro'),preview,'Switching back reuses the previous treatment');
 assert.equal(processed,afterPreview+1,'Cache hit must not run the filter again');
 const exported=await r.render(image,'magicpro');
 assert.equal(exported.height,1600);assert.equal(exported.width,1200);
 assert.notEqual(preview,exported,'Display-sized previews must never replace full-size exports');
 const large=await r.preview({width:3464,height:4619},'magicpro');
 assert.ok(Math.max(large.width,large.height)<=1400);assert.ok(large.width*large.height<=1_402_000);
 assert.equal(await r.preview(image,'bw',{},()=>false),null,'Stale preview requests stop before allocation');
 console.log('PASS: stale work skipped; filter switches cached; preview pixels bounded; exports retain full source dimensions.');
})();
